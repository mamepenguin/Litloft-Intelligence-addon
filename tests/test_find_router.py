class TestFindRequestSchema:
    def test_minimum_question_required(self):
        with pytest.raises(Exception):
            FindRequest()  # type: ignore[call-arg]

    def test_empty_question_rejected(self):
        with pytest.raises(Exception):
            FindRequest(question="")

    def test_question_max_length_enforced(self):
        # Mirror AskRequest's 1000-char ceiling so giant queries can't
        # DoS the LLM behind the decomposer.
        with pytest.raises(Exception):
            FindRequest(question="x" * 1001)

    def test_overrides_optional(self):
        body = FindRequest(question="hello world question")
        assert getattr(body, "overrides", None) in (None, {})

    def test_overrides_accepted_when_dict(self):
        body = FindRequest(
            question="hello world question",
            overrides={
                "time_range": "none",
                "personal_scope": "viewed",
                "file_type_hint": "video",
                "semantic_query": "SF",
            },
        )
        assert body.overrides["personal_scope"] == "viewed"

    def test_limit_within_reasonable_bounds(self):
        # The service caps at 20 results per spec §3.2; reject silly
        # client values defensively.
        body = FindRequest(question="valid question text", limit=20)
        assert body.limit == 20
        with pytest.raises(Exception):
            FindRequest(question="valid question text", limit=0)
