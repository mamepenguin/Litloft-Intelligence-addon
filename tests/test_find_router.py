def _stub_find_response(
    *,
    results: list[dict] | None = None,
    decomposed: dict | None = None,
    total: int | None = None,
    limit: int = 20,
):
    """Build a plausible FindResponse-like object for service stubs.

    The router test layer doesn't care about the precise dataclass /
    pydantic model used internally by the service — we just need
    ``find_files`` to return *something* the router can serialise. A
    plain dict is the lowest-friction shape; we wrap it in MagicMock
    only for tests that need to spy on attribute access.
    """
    payload = {
        "decomposed": decomposed
        or {
            "time_range": {
                "kind": "none",
                "value": "none",
                "after": None,
                "before": None,
            },
            "personal_scope": "none",
            "file_type_hint": "none",
            "semantic_query": "",
            "category_expansion": [],
        },
        "results": results if results is not None else [],
        "total": total if total is not None else (len(results) if results else 0),
        "limit": limit,
    }
    return payload


def _result_item(
    *,
    file_id: str = "f-abc123",
    score: float = 0.82,
    hit_kind: str = "transcript",
    hit_text: str = "...宇宙船が時空を超えて...",
    name: str = "Interstellar.mp4",
    file_type: str = "video",
) -> dict:
    return {
        "file_id": file_id,
        "score": score,
        "hit": {
            "kind": hit_kind,
            "location": {"start_seconds": 415.2, "end_seconds": 460.0},
            "text": hit_text,
        },
        "file": {
            "name": name,
            "file_type": file_type,
            "thumbnail_url": f"/api/files/{file_id}/thumbnail",
            "viewed_at": "2026-04-27T19:30:00Z",
        },
    }


