class TestFindEndpointOverrides:
    """Body ``overrides`` are chip-edit reposts.

    When the user clicks the × on a chip the frontend rebuilds the
    structured query and re-POSTs with ``overrides`` populated. The
    router must forward ``overrides`` to the service, which uses it
    INSTEAD OF re-running query_decomposer.
    """

    @pytest.mark.asyncio
    async def test_overrides_are_forwarded_to_service(
        self, find_enabled, monkeypatch
    ):
        captured: dict = {}

        async def _capture(**kwargs):
            captured.update(kwargs)
            return _stub_find_response()

        monkeypatch.setattr("app.routers.rag.find_files", _capture)

        overrides = {
            "time_range": "none",  # chip × on time
            "personal_scope": "viewed",
            "file_type_hint": "video",
            "semantic_query": "SF",
        }
        body = FindRequest(
            question="先週観た映画でSF",
            overrides=overrides,
        )

        await find_endpoint(
            body=body,
            access_token="tok",
            drive="movies",
            viewer_id="x" * 16,
        )

        assert captured.get("overrides") == overrides

    @pytest.mark.asyncio
    async def test_overrides_omitted_when_not_provided(
        self, find_enabled, monkeypatch
    ):
        """Default chip-less request -> overrides is None / absent.

        The service can then run query_decomposer on its own.
        """
        captured: dict = {}

        async def _capture(**kwargs):
            captured.update(kwargs)
            return _stub_find_response()

        monkeypatch.setattr("app.routers.rag.find_files", _capture)

        body = FindRequest(question="先週観た映画でSF")
        await find_endpoint(
            body=body,
            access_token="tok",
            drive="movies",
            viewer_id="x" * 16,
        )

        # overrides is None by default — the service interprets that as
        # "decompose from scratch".
        assert captured.get("overrides") in (None, {})


