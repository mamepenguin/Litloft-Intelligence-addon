class TestFindEndpointResponseShape:
    @pytest.mark.asyncio
    async def test_returns_200_with_full_response_shape(
        self, find_enabled, monkeypatch
    ):
        """Spec §3.2 requires decomposed + results + total + limit."""
        decomposed = {
            "time_range": {
                "kind": "relative",
                "value": "last_week",
                "after": "2026-04-23T00:00:00Z",
                "before": "2026-04-30T00:00:00Z",
            },
            "personal_scope": "viewed",
            "file_type_hint": "video",
            "semantic_query": "SF",
            "category_expansion": [
                "science fiction",
                "宇宙船",
                "ロボット",
                "ディストピア",
            ],
        }
        items = [_result_item(file_id="f-abc123"), _result_item(file_id="f-def456")]

        monkeypatch.setattr(
            "app.routers.rag.find_files",
            AsyncMock(
                return_value=_stub_find_response(
                    results=items, decomposed=decomposed, total=8, limit=20
                )
            ),
        )

        body = FindRequest(question="先週観た映画の中で SF っぽいのどれ？")
        result = await find_endpoint(
            body=body,
            access_token="tok",
            drive="movies",
            viewer_id="x" * 16,
        )

        # The result is the JSON body or a dict-shaped pydantic model.
        # Either way, the spec keys must be present.
        payload = result if isinstance(result, dict) else result.model_dump()
        assert set(payload.keys()) >= {
            "decomposed",
            "results",
            "total",
            "limit",
        }
        assert payload["decomposed"]["time_range"]["value"] == "last_week"
        assert payload["decomposed"]["personal_scope"] == "viewed"
        assert payload["decomposed"]["file_type_hint"] == "video"
        assert payload["decomposed"]["semantic_query"] == "SF"
        assert payload["decomposed"]["category_expansion"] == [
            "science fiction",
            "宇宙船",
            "ロボット",
            "ディストピア",
        ]
        assert payload["limit"] == 20
        assert payload["total"] == 8
        assert len(payload["results"]) == 2

    @pytest.mark.asyncio
    async def test_response_decomposed_has_required_keys(
        self, find_enabled, monkeypatch
    ):
        """``decomposed`` block must include all five spec-mandated keys.

        Even when the LLM emits "no signal" the keys MUST be present so
        the frontend can render its chip layout without conditional
        existence checks.
        """
        empty_decomposed = {
            "time_range": {
                "kind": "none",
                "value": "none",
                "after": None,
                "before": None,
            },
            "personal_scope": "none",
            "file_type_hint": "none",
            "semantic_query": "",
            "category_expansion": [],
        }
        monkeypatch.setattr(
            "app.routers.rag.find_files",
            AsyncMock(
                return_value=_stub_find_response(
                    results=[], decomposed=empty_decomposed, total=0
                )
            ),
        )

        body = FindRequest(question="anything goes here")
        result = await find_endpoint(
            body=body,
            access_token=None,
            drive="movies",
            viewer_id=None,
        )

        payload = result if isinstance(result, dict) else result.model_dump()
        for key in (
            "time_range",
            "personal_scope",
            "file_type_hint",
            "semantic_query",
            "category_expansion",
        ):
            assert key in payload["decomposed"], (
                f"decomposed missing required spec key: {key}"
            )

    @pytest.mark.asyncio
    async def test_empty_results_returns_200_not_404(
        self, find_enabled, monkeypatch
    ):
        """Zero hits is a normal outcome, not an error."""
        monkeypatch.setattr(
            "app.routers.rag.find_files",
            AsyncMock(return_value=_stub_find_response(results=[], total=0)),
        )

        body = FindRequest(question="something with no matches at all")
        result = await find_endpoint(
            body=body,
            access_token="tok",
            drive="movies",
            viewer_id=None,
        )
        # If the endpoint mistakenly raised 404 we wouldn't reach here.
        payload = result if isinstance(result, dict) else result.model_dump()
        assert payload["results"] == []
        assert payload["total"] == 0

    @pytest.mark.asyncio
    async def test_hit_text_comes_from_retrieve_segment_not_llm(
        self, find_enabled, monkeypatch
    ):
        """Spec §3.3: Stage E_find calls the LLM ZERO times.

        The `hit.text` field must be populated from the retrieved
        segment text directly (tier 1 = primary source per hako
        ``SKiYgE6GtttlQW7fEwAY6``). LLM-generated reasoning text would
        violate the no-hallucination guarantee that motivates Find mode
        over Ask mode.
        """
        retrieve_text = "...this is the verbatim retrieved segment..."
        monkeypatch.setattr(
            "app.routers.rag.find_files",
            AsyncMock(
                return_value=_stub_find_response(
                    results=[_result_item(hit_text=retrieve_text)]
                )
            ),
        )

        body = FindRequest(question="what is this about")
        result = await find_endpoint(
            body=body,
            access_token="tok",
            drive="movies",
            viewer_id=None,
        )

        payload = result if isinstance(result, dict) else result.model_dump()
        assert payload["results"][0]["hit"]["text"] == retrieve_text


