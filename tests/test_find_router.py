"""Tests for app.routers.rag — POST /find endpoint (Find mode).

Spec: ``docs/superpowers/specs/2026-04-30-intelligence-find-mode.md`` §3.2.

Find mode is the file-listing sibling of Ask mode. It reuses Stage A-D
(decompose / history filter / category expansion / scoped retrieval)
but skips Stage E (LLM answer generation) entirely. The router returns
single-shot JSON, NOT SSE — there is no LLM token stream to multiplex.

These tests exercise the router-level concerns:

* Drive header gating: ``X-Lit-Drive`` is required, mirroring /ask.
* Feature gating: ``features.rag=False`` and ``LLM disabled`` both
  reject the request as 4xx (the same gating as /ask, since Find
  shares the LLM-driven Stages A + C).
* Body ``overrides`` (chip-edited query) take precedence over the
  LLM-decomposed query.
* ``viewer_id`` graceful fallback: if the request asks for personal
  scope but no ``X-Lit-Viewer-Id`` header is present, the endpoint
  must NOT 4xx — instead Stage B is silently skipped.
* Response shape from spec §3.2: ``decomposed``, ``results``, ``total``,
  ``limit``, with hit text populated from the retrieve segment (NOT
  generated by an LLM).
* Empty results return 200 with an empty array, NOT 404.

All tests RED until Phase 4 (the new ``/find`` endpoint, ``FindRequest``
/ ``FindResponse`` schemas, and the ``find_files`` service function)
land. The import surface itself is the gate — if any of the new symbols
is missing, the module fails to import and pytest reports the failure
as a collection error which is the strongest possible RED signal.
"""

