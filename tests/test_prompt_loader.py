class TestAutoTagsUserPrompt:
    @staticmethod
    def _file(**over) -> dict:
        return {
            "filename": "f.mp4",
            "title": "",
            "description": "",
            "tags_text": "",
            **over,
        }

    def _out(self, indexed=None, existing=None, candidates=None) -> str:
        from app.workers import auto_tags

        return auto_tags._build_user_prompt(
            indexed if indexed is not None else self._file(),
            "video",
            "body text",
            existing if existing is not None else [],
            candidates,
        )

    def test_omits_a_title_that_only_repeats_the_filename(self) -> None:
        assert "f.mp4" not in self._out(self._file(title="f.mp4")).replace(
            "Filename: f.mp4", ""
        )

    def test_carries_a_title_that_differs_from_the_filename(self) -> None:
        assert "Another title" in self._out(self._file(title="Another title"))

    def test_says_none_when_the_file_has_no_tags_yet(self) -> None:
        assert "none" in self._out(existing=[])
        out = self._out(existing=["existing1", "existing2"])
        assert "existing1, existing2" in out

    def test_adds_no_candidate_section_without_candidates(self) -> None:
        from app.workers import auto_tags

        assert "Reference candidates" not in self._out()
        empty = auto_tags.TagCandidates(clip=[], tfidf=[], knn=[])
        assert "Reference candidates" not in self._out(candidates=empty)

    def test_lists_each_candidate_source_that_has_entries(self) -> None:
        from app.workers import auto_tags

        out = self._out(
            candidates=auto_tags.TagCandidates(
                clip=["clip1"], tfidf=["tfidf1"], knn=["knn1"]
            )
        )

        assert "Reference candidates" in out
        assert "Tags from similar files: knn1" in out
        assert "Image analysis candidates: clip1" in out
        assert "Keyword extraction candidates: tfidf1" in out
        # k-NN leads: "similar tagged files" is the strongest signal.
        assert out.index("knn1") < out.index("clip1") < out.index("tfidf1")

    def test_omits_a_candidate_source_that_is_empty(self) -> None:
        from app.workers import auto_tags

        out = self._out(
            candidates=auto_tags.TagCandidates(clip=[], tfidf=["tfidf1"], knn=[])
        )

        assert "Reference candidates" in out
        assert "Keyword extraction candidates: tfidf1" in out
        assert "Tags from similar files" not in out
        assert "Image analysis candidates" not in out


