def test_common_rules_matches_golden() -> None:
    """The one include with two consumers, so an edit reaches both."""
    assert render("summaries/_common_rules.jinja2") == _golden(
        "summaries_common_rules.txt"
    )


def test_both_summary_system_prompts_carry_the_shared_rules(_set_lang) -> None:
    from app.workers import summaries

    _set_lang("auto")
    shared = render("summaries/_common_rules.jinja2").strip()
    assert shared
    assert shared in summaries._build_system_prompt()
    assert shared in summaries._build_detailed_system_prompt()


