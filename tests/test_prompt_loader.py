class TestRefinePrompts:
    def test_system_prompt_asks_for_the_configured_script(self, _set_lang) -> None:
        from app.workers import refine

        _set_lang("ja")
        assert "。" in refine._build_system_prompt()
        _set_lang("en")
        out = refine._build_system_prompt()
        assert "periods, commas" in out
        assert "。" not in out

    def test_an_unlisted_language_falls_back_rather_than_naming_one(
        self, _set_lang
    ) -> None:
        from app.workers import refine

        _set_lang("fr")
        out = refine._build_system_prompt()

        assert out == refine.render(
            "refine/system.jinja2",
            punctuation_instruction=refine._DEFAULT_PUNCTUATION,
        )

    def test_user_prompt_is_json_carrying_every_chunk(self) -> None:
        from app.workers import refine

        class _Chunk:
            def __init__(self, cid: int, text: str | None) -> None:
                self.id = cid
                self.text = text

        out = refine._build_user_prompt(
            [_Chunk(1, "hello"), _Chunk(2, "world"), _Chunk(3, None)]
        )
        payload = json.loads(out[out.index("[") : out.rindex("]") + 1])

        assert payload == [
            {"id": 1, "text": "hello"},
            {"id": 2, "text": "world"},
            # A chunk with no text stays in the window: dropping it would
            # desync the id set `_parse_llm_response` checks against.
            {"id": 3, "text": ""},
        ]


