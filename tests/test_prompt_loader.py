class TestRagAnswerPrompt:
    def test_system_prompt_names_the_configured_language(self) -> None:
        from app.rag import prompt as rag_prompt

        assert "Japanese" in rag_prompt.build_system_prompt("ja")
        assert "English" in rag_prompt.build_system_prompt("en")

    def test_system_prompt_names_none_on_auto(self) -> None:
        from app.rag import prompt as rag_prompt

        out = rag_prompt.build_system_prompt("auto")

        assert "Japanese" not in out
        assert "English" not in out

    def test_a_language_outside_the_table_still_reaches_the_model(self) -> None:
        """The `.get` fallback; the table holds only ja and en."""
        from app.rag import prompt as rag_prompt

        assert "Answer in fr" in rag_prompt.build_system_prompt("fr")

    def test_user_prompt_is_well_formed_without_context(self) -> None:
        from app.rag import prompt as rag_prompt

        out = rag_prompt.build_user_prompt("the query", [])

        assert "the query" in out
        assert "file_id" not in out

    def test_user_prompt_carries_each_file_and_its_snippets(self) -> None:
        from app.rag import prompt as rag_prompt
        from app.rag.context import ContextSnippet, FileContext

        ctx = FileContext(
            file_id="abc123",
            filename="video.mp4",
            drive="movies",
            file_type="video",
            title="title",
            description="description",
            snippets=(
                ContextSnippet(
                    source="transcript", location="0:45", text="snippet text"
                ),
                ContextSnippet(source="metadata", location=None, text="meta snippet"),
            ),
            total_chars=42,
        )

        out = rag_prompt.build_user_prompt("the query", [ctx])

        assert "abc123" in out
        assert "video.mp4" in out
        assert "snippet text" in out
        assert "0:45" in out
        # A snippet without a location still reaches the model.
        assert "meta snippet" in out


