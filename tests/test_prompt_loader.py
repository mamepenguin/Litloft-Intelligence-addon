"""What each prompt builder decides, and the two prompts a shared include reaches.

Assertions name the decision a builder makes — a field suppressed, a section
added, a language line chosen — rather than the whole rendered text, so
rewording a template does not force a regeneration that a logic regression
can ride along in.

``summaries/_common_rules.jinja2`` is the exception. Two system prompts
include it, so an edit there changes both without naming either. That file
keeps a byte-identical golden, regenerated by ``golden_prompts/_baseline.py``,
and both prompts are checked for carrying it.
"""

from __future__ import annotations

import json
from pathlib import Path

import pytest
from jinja2 import UndefinedError

from app.prompt_loader import render


GOLDEN_DIR = Path(__file__).resolve().parent / "golden_prompts"


def _golden(name: str) -> str:
    return (GOLDEN_DIR / name).read_bytes().decode("utf-8")


