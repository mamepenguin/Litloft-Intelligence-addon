def _summary_file(**over) -> dict:
    return {"filename": "test.mp4", "title": "", "description": "", **over}


@pytest.mark.parametrize(
    "build",
    ["_build_user_prompt", "_build_detailed_user_prompt"],
)
class TestSummariesUserPrompt:
    """Both user prompts drop the same fields on the same conditions."""

    @staticmethod
    def _out(build: str, indexed: dict, *, was_truncated: bool = False) -> str:
        from app.workers import summaries

        return getattr(summaries, build)(
            indexed, "video", "body text", was_truncated=was_truncated
        )

    def test_omits_title_and_description_when_absent(self, build) -> None:
        out = self._out(build, _summary_file())

        assert "Title:" not in out
        assert "Description:" not in out
        assert "test.mp4" in out
        assert "body text" in out

    def test_carries_title_and_description_when_present(self, build) -> None:
        out = self._out(
            build, _summary_file(title="A title", description="A description")
        )

        assert "Title: A title" in out
        assert "Description: A description" in out

    def test_omits_a_title_that_only_repeats_the_filename(self, build) -> None:
        out = self._out(build, _summary_file(title="test.mp4"))

        assert "Title:" not in out

    def test_marks_a_truncated_body_and_says_nothing_otherwise(
        self, build
    ) -> None:
        whole = self._out(build, _summary_file())
        excerpt = self._out(build, _summary_file(), was_truncated=True)

        assert "excerpt" not in whole
        assert "excerpt" in excerpt


